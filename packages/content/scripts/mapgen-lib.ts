import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));

export const GENERATED_DIR = path.join(here, '../data/districts/generated');
export const BARREL_FILE = path.join(GENERATED_DIR, 'index.ts');

/** Rewrites `generated/index.ts` from whatever `.json` files currently sit in `GENERATED_DIR`.
 * Shared by `generate-maps.ts` (after writing new candidates) and `prune-maps.ts` (after
 * deleting rejected ones), so the barrel is never hand-edited or allowed to drift from disk. */
export async function rewriteBarrel(): Promise<string[]> {
  const files = (await readdir(GENERATED_DIR)).filter((f) => f.endsWith('.json')).sort();
  const barrel = [
    '// Auto-generated by `pnpm --filter @wetwire/content gen-maps` / `prune-maps`. Do not',
    '// hand-edit — rerun the script instead.',
    ...files.map((f, i) => `import m${i} from './${f}' with { type: 'json' };`),
    '',
    `export const generatedDistricts: readonly unknown[] = [${files.map((_, i) => `m${i}`).join(', ')}];`,
    '',
  ].join('\n');
  await writeFile(BARREL_FILE, barrel);
  return files;
}
